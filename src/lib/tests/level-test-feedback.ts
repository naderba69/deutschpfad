export function getLevelTestFeedback(pct: number, passed: boolean): string {
  if (!passed) return "لم تبلغ حدّ النجاح في هذا الاختبار؛ راجع المهارات الأضعف ثم أعد الاختبار";
  if (pct >= 90) {
    return "Sehr gut — نتيجة مرتفعة في هذا الاختبار السريع؛ لا تكفي وحدها للحكم على الجاهزية للامتحان";
  }
  if (pct >= 75) return "Gut — نتيجة جيدة في هذا الاختبار؛ واصل التدريب وراجع المهارات الأضعف";
  return "اجتزت حدّ النجاح في هذا الاختبار فقط؛ واصل تقوية المهارات الأضعف";
}
