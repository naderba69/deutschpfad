/** سياق درس يُمرَّر للمعلّم (من صفحة الدرس) */
export interface LessonBrief {
  titleAr: string;
  titleDe: string;
  summary: string;
  theoryTitles: string[];
}

function lessonBlock(lesson?: LessonBrief): string {
  if (!lesson) return "";
  return (
    "\n── سياق الدرس الذي يدرسه المتعلّم الآن ──\n" +
    `عنوان الدرس: ${lesson.titleAr} (${lesson.titleDe})\n` +
    `نبذة: ${lesson.summary}\n` +
    `القواعد المغطاة: ${lesson.theoryTitles.join("؛ ")}\n` +
    "إن كان السؤال متعلقاً بالدرس، فاربط إجابتك بقواعده ومفرداته."
  );
}

