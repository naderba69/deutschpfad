/** تقييم كتابة بمعايير Goethe الرسمية — المعايير الأربعة + درجة تقريبية + حكم */
export function goetheWritingPrompt(input: {
  text: string;
  level: string;
  taskType: string;
  taskDescription: string;
}): { system: string; user: string } {
  return {
    system:
      BASE +
      "\nمهمتك: تقييم نص ألماني كتبه متعلم وفق **معايير Goethe-Zertifikat الرسمية الأربعة** لامتحان الكتابة.\n" +
      "قيّم كل معيار من 1 إلى 5 (5 = ممتاز)، ثم احسب النسبة المئوية (الدرجة الكلية = مجموع المعايير الأربعة ÷ 20 × 100).\n" +
      "المعايير الأربعة:\n" +
      "1) Erfüllung — إنجاز المهمة: هل غُطيت كل نقاط المهمة؟ هل نوع النص والأسلوب مناسبان؟\n" +
      "2) Kohärenz — البنية والترابط: فقرات منطقية، روابط (Redemittel)، انتقالات سلسة.\n" +
      "3) Wortschatz — المفردات: مدى مناسب للمستوى، دقة اختيار الكلمات، كولوكيشنات، تنويع.\n" +
      "4) Struktur — القواعد: تنوع تركيبي (جمل ثانوية، Konjunktiv، مجهول...) وصحة نحوية.\n" +
      "أخرج النتيجة بهذا الشكل الدقيق (كل سطر يبدأ بالوسم):\n" +
      "###معيار1: الاسم — الدرجة/5\n" +
      "###ملاحظة1: ملاحظة بالعربية (سطر واحد واضح)\n" +
      "###معيار2: الاسم — الدرجة/5\n" +
      "###ملاحظة2: ...\n" +
      "###معيار3: الاسم — الدرجة/5\n" +
      "###ملاحظة3: ...\n" +
      "###معيار4: الاسم — الدرجة/5\n" +
      "###ملاحظة4: ...\n" +
      "###النسبة: XX%\n" +
      "###الحكم: Bestanden (60-74) / Gut (75-89) / Sehr gut (90-100) / Nicht bestanden (<60)\n" +
      "###أخطاء: قائمة (الجملة ← الصحيحة — نوع الخطأ — سبب مختصر بالعربية)، وإن لم توجد اكتب «لا توجد أخطاء ملحوظة».\n" +
      "###توصية: جملة واحدة: ما أهم شيء يحسّن الدرجة؟\n" +
      "لا تكتب أي شيء خارج هذه الوسوم.",
    user:
      `مستوى المتعلم: ${input.level}\n` +
      `نوع المهمة: ${input.taskType}\n` +
      `وصف المهمة (كما في الامتحان): ${input.taskDescription}\n\n` +
      `نص المتعلم:\n${input.text}`,
  };
}

/** شريك المحادثة الصوتية — معلّم يتحدث بالألمانية بمستوى المتعلم */
export function voiceTeacherSystemPrompt(
  level: string,
  topic: string,
): { system: string; user: string } {
  return {
    system:
      BASE +
      "\nمهمتك الآن: **شريك محادثة ألماني** (وليس معلّماً يشرح بالعربية).\n" +
    "القواعد الصارمة:\n" +
    "1) ردّك **بالألمانية فقط** (لا عربية إطلاقاً في الرد الرئيسي).\n" +
    `2) مستوى ${level}: جمل قصيرة بسيطة (A1: 3-5 كلمات، A2: جملة-جملتان، B1: 2-3 جمل بسيطة، B2: 3-4 جمل متنوعة).\n` +
    "3) بعد ردّك، **اسأل سؤالاً واحداً** لمواصلة المحادثة (كما يفعل شريك حقيقي).\n" +
    `4) الموضوع: ${topic} — التزم به. إن غيرت الموضوع سؤالاً، اعترف وعد إليه بلطف.\n` +
    "5) إن كان نص المتعلم فيه خطأ بسيط، أعد الجملة مصححة **داخل ردّك** بشكل طبيعي (مثل: „Ja, gestern bin ich ...“) دون محاضرة.\n" +
    "6) إن لم تفهم، قل: „Entschuldigung, kannst du das bitte wiederholen?“\n" +
    "7) لا تتجاوز 3-4 جمل في كل رد.\n" +
    "8) أرفق في نهاية ردّك سطراً يبدأ بـ «###تصحيح:» يوضح أي خطأ وجدته بالعربية (أو «لا أخطاء» إن لم يوجد). هذا السطر لا يُنطق صوتياً.",
    user: `المحادثة الآن بيني (المتعلم) وبينك (الشريك الألماني) حول: ${topic}. أهلاً بك!`,
  };
}
