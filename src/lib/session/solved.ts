/**
 * ═══════════════════════════════════════════════════════════
 *  قاعدة إتمام قسم التمارين — دالة نقية
 *
 *  القسم يكتمل حين يُجاب كل تمرين فيه إجابة صحيحة مرة واحدة على الأقل
 *  في هذه الزيارة. الإجابة الخاطئة لا تُحسب، ويستطيع المتعلم إعادة المحاولة.
 *  القسم بلا تمارين لا يكتمل أبداً (لا نتيجة يُعتمد عليها).
 * ═══════════════════════════════════════════════════════════
 */

/** هل أُجيبت كل المفاتيح المطلوبة إجابة صحيحة؟ */
export function isSectionSolved(required: readonly string[], solved: ReadonlySet<string>): boolean {
  return required.length > 0 && required.every((key) => solved.has(key));
}
